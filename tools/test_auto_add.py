"""Tests for tools/auto_add.py and the allow list of tools/openrazer_facts.py: python3 -I -m unittest discover -s tools -p 'test_*.py'"""

import json
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import auto_add  # noqa: E402
import openrazer_facts  # noqa: E402

HEADER = "//! Generated by tools/openrazer_facts.py\n//! (https://github.com/openrazer/openrazer, GPL-2.0, commit {}): product ids\n"
PIN, NEWER = "a" * 40, "b" * 40


def model(pid):
    return f"    Model {{\n        vendor_id: 0x1532,\n        product_ids: &[0x{pid:04X}],\n        name: \"x\",\n    }},\n"


def left_out(define):
    return f'    "USB_DEVICE_ID_RAZER_{define} (receiver or wireless dongle)",\n'


def table(pids, out=(), commit=PIN):
    return (
        HEADER.format(commit) + "pub const MODELS: &[Model] = &[\n" + "".join(model(p) for p in pids) + "];\n\n"
        "pub const LEFT_OUT: &[&str] = &[\n" + "".join(left_out(d) for d in out) + "];\n"
    )


class Shapes(unittest.TestCase):
    def test_usb_id_and_branch(self):
        self.assertTrue(auto_add.valid_usb("1532:00c1"))
        for bad in ("1532:00C1", "1532:c1", "1532-00c1", "1532:00c1;rm", "", "1532:00c1\n"):
            self.assertFalse(auto_add.valid_usb(bad), bad)
        self.assertEqual(auto_add.branch_name("1532:00c1"), "test/auto-1532-00c1")

    def test_the_pinned_commit_is_the_one_in_the_header(self):
        self.assertEqual(auto_add.pinned_commit(table([1])), PIN)
        self.assertIsNone(auto_add.pinned_commit("//! no commit here\n"))
        # The real tables name their commit in full.
        real = (auto_add.ROOT / auto_add.GENERATORS[("openrazer", "1532")]["table"]).read_text()
        self.assertRegex(auto_add.pinned_commit(real), r"^[0-9a-f]{40}$")

    def test_the_allow_list_gets_the_id_once_in_order(self):
        text = auto_add.with_allowed('{"allow": []}\n', "1532:00c1")
        text = auto_add.with_allowed(text, "1532:00b7")
        text = auto_add.with_allowed(text, "1532:00c1")
        self.assertEqual(json.loads(text), {"allow": ["1532:00b7", "1532:00c1"]})
        self.assertEqual(json.loads(auto_add.with_allowed("", "1532:00c1")), {"allow": ["1532:00c1"]})

    def test_the_commit_message_has_the_trailer_notify_reads(self):
        sys.path.insert(0, str(Path(__file__).resolve().parent))
        import notify

        message = auto_add.commit_message("Razer Viper V3 Pro", "1532:00c1", "85", "openrazer", PIN)
        self.assertEqual(notify.trailers(message), [85])
        self.assertTrue(message.startswith("Razer Viper V3 Pro (1532:00c1)"))


class CheckDiff(unittest.TestCase):
    def test_a_dongle_the_allow_list_lets_through_is_accepted(self):
        old = table([1, 2], out=["VIPER_V3_PRO_WIRELESS", "OTHER_RECEIVER"])
        new = table([1, 2, 0xC1], out=["OTHER_RECEIVER"])
        self.assertIsNone(auto_add.check_diff(old, new, "1532:00c1"))

    def test_the_commit_in_the_header_may_change(self):
        self.assertIsNone(auto_add.check_diff(table([1]), table([1, 0xC1], commit=PIN[::-1]), "1532:00c1"))

    def test_an_id_the_generator_does_not_produce_fails(self):
        old = table([1], out=["VIPER_V3_PRO_WIRELESS"])
        self.assertIn("does not produce", auto_add.check_diff(old, old, "1532:00c1"))

    def test_an_id_in_the_table_already_fails(self):
        self.assertIn("already", auto_add.check_diff(table([1, 0xC1]), table([1, 0xC1]), "1532:00c1"))

    def test_a_second_new_device_fails(self):
        self.assertIn("this device alone", auto_add.check_diff(table([1]), table([1, 2, 0xC1]), "1532:00c1"))
        self.assertIn("this device alone", auto_add.check_diff(table([1]), table([1, 0xC1, 2]), "1532:00c1"))

    def test_a_removed_model_or_a_changed_fact_fails(self):
        self.assertIn("this device alone", auto_add.check_diff(table([1, 2]), table([1, 0xC1]), "1532:00c1"))
        changed = table([1, 0xC1]).replace('name: "x"', 'name: "y"', 1)
        self.assertIn("this device alone", auto_add.check_diff(table([1]), changed, "1532:00c1"))

    def test_something_else_leaving_the_rest_of_the_file_fails(self):
        old = table([1], out=["A", "B"])
        self.assertIsNone(auto_add.check_diff(old, table([1, 0xC1], out=["A"]), "1532:00c1"))
        self.assertIn("changes something else", auto_add.check_diff(old, table([1, 0xC1], out=["A"]).replace("pub const MODELS", "pub const MODELZ"), "1532:00c1"))


class AllowList(unittest.TestCase):
    def test_ids_of_the_file_are_product_ids_of_razer_only(self):
        with tempfile.TemporaryDirectory() as d:
            path = Path(d) / "auto-add.json"
            self.assertEqual(openrazer_facts.allowed_pids(path), set())
            path.write_text(json.dumps({"allow": ["1532:00c1", "046d:c08b", "nonsense"]}))
            self.assertEqual(openrazer_facts.allowed_pids(path), {0xC1})

    def test_the_file_in_the_repository_is_valid(self):
        data = json.loads((auto_add.ROOT / auto_add.ALLOW).read_text())
        self.assertIsInstance(data["allow"], list)


class Build(unittest.TestCase):
    """The parts of build() that need no source and no cargo: what it refuses."""

    def repo(self, d, devices):
        run = lambda *a: subprocess.run(["git", "-C", d, "-c", "user.name=t", "-c", "user.email=t@t", *a], check=True, capture_output=True)
        run("init", "-q")
        (Path(d) / "site").mkdir()
        (Path(d) / "site/devices.json").write_text(json.dumps({"devices": devices}))
        run("add", "-A")
        run("commit", "-q", "-m", "x")

    def test_a_known_device_is_nothing_to_do(self):
        with tempfile.TemporaryDirectory() as d:
            self.repo(d, [{"usb_ids": ["1532:00c1"]}])
            with self.assertRaises(auto_add.Skip):
                auto_add.build("1532:00c1", "85", Path(d) / "src", Path(d))

    def test_bad_input_and_vendors_without_a_generator_fail(self):
        with tempfile.TemporaryDirectory() as d:
            self.repo(d, [])
            for usb, issue in (("1532:00c1;", "85"), ("1532:00c1", "8x"), ("046d:c08b", "85"), ("1038:1234", "85")):
                with self.subTest(usb=usb, issue=issue), self.assertRaises(auto_add.Fail):
                    auto_add.build(usb, issue, Path(d) / "src", Path(d))


