//! app/preview/data.json: the data the screenshots show, from PeriHub's own code and real device
//! data in the repository: the five profiles of a real G502 HERO (the test fixtures) and the Apex 3
//! TKL's key catalogue and factory key map.

use perihub_core::apex::{KeyBinding, keys};
use perihub_core::hidpp::profile::{ProfileSettings, parse_directory};
use perihub_core::keyboard::Keymap;
use perihub_core::mouse::MouseProfile;
use serde_json::json;

pub const PATH: &str = "app/preview/data.json";

const G502_BUTTONS: usize = 11;
const G502_PROFILES: usize = 5;
/// Caps Lock as Esc on the normal layer: one remapped key, so the key page shows what a change looks like.
const CAPS_LOCK: u8 = 0x39;
const ESCAPE: u8 = 0x29;

fn sector(id: u16) -> Vec<u8> {
    let path = crate::root().join(format!("crates/perihub-core/tests/fixtures/g502/sector_{id:04x}.bin"));
    std::fs::read(&path).unwrap_or_else(|e| panic!("{}: {e}", path.display()))
}

pub fn render() -> String {
    let enabled = parse_directory(&sector(0), G502_PROFILES);
    let profiles: Vec<MouseProfile> = (1..=G502_PROFILES as u16)
        .map(|n| MouseProfile {
            number: n as u8,
            enabled: enabled[n as usize - 1],
            settings: ProfileSettings::parse(&sector(n), G502_BUTTONS).expect("fixture profile"),
        })
        .collect();

    let sources: Vec<u8> = (0..=255u8).filter(|&u| keys::is_remappable_source(u)).collect();
    let mut keymap = Keymap { normal: Default::default(), steelseries: Default::default() };
    for &source in &sources {
        keymap.normal.insert(source, KeyBinding::factory(0, source));
        keymap.steelseries.insert(source, KeyBinding::factory(1, source));
    }
    keymap.normal.insert(CAPS_LOCK, KeyBinding::Key { usage: ESCAPE });

    let data = json!({
        "about": "Generated by cargo xtask gen from the G502 HERO test fixtures and the Apex 3 TKL tables.",
        "mouse_profiles": profiles,
        "key_catalog": { "targets": keys::TARGET_KEYS, "sources": sources },
        "keymap": keymap,
    });
    serde_json::to_string_pretty(&data).unwrap() + "\n"
}
